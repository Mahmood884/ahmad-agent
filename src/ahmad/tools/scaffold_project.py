"""Project scaffolding skill — generates a safe, standard project structure."""
from pathlib import Path
from ahmad.execution.mock_tool import ToolResult

class ScaffoldProjectTool:
    name = "scaffold_project"
    version = "1.0"

    def __init__(self, root: str | Path | None = None):
        self.root = Path(root).expanduser().resolve() if root else Path.cwd().resolve()

    def run(self, action: str) -> ToolResult:
        # Format: scaffold_project:name=my_project|type=python-cli
        if not action.startswith("scaffold_project:"):
            return ToolResult(False, self.name, "ERROR: Action must start with 'scaffold_project:'", None)
            
        payload = action[len("scaffold_project:"):]
        parts = payload.split("|")
        
        project_name = None
        project_type = "python-cli"
        
        for part in parts:
            if part.startswith("name="):
                project_name = part.split("=", 1)[1].strip()
            elif part.startswith("type="):
                project_type = part.split("=", 1)[1].strip()
                
        if not project_name or len(project_name) < 3:
            return ToolResult(False, self.name, "ERROR: Valid 'name' is required (min 3 chars)", None)
            
        if not project_name.isidentifier():
            return ToolResult(False, self.name, "ERROR: Project name must be a valid Python identifier", None)

        try:
            target_dir = (self.root / project_name).resolve()
            
            # Security Guard: Prevent overwriting existing directories
            if target_dir.exists():
                return ToolResult(False, self.name, f"DENIED: Directory '{target_dir}' already exists.", None)
                
            # Security Guard: Ensure it's under the allowed root
            if not target_dir.is_relative_to(self.root):
                return ToolResult(False, self.name, f"DENIED: Path must be under {self.root}", None)

            # Create directory
            target_dir.mkdir(parents=True, exist_ok=True)
            created_files = []

            # 1. .gitignore
            gitignore_content = "__pycache__/\n*.py[cod]\n*$py.class\n*.so\n.Python\nenv/\nbuild/\ndevelop-eggs/\ndist/\ndownloads/\neggs/\n.eggs/\nlib/\nlib64/\nparts/\nsdist/\nvar/\nwheels/\n*.egg-info/\n.installed.cfg\n*.egg\n"
            (target_dir / ".gitignore").write_text(gitignore_content, encoding="utf-8")
            created_files.append(".gitignore")

            # 2. README.md
            readme_content = f"# {project_name}\n\nGenerated by Ahmad Agent.\n\n## Setup\n```bash\npython -m venv .venv\nsource .venv/bin/activate\npip install -e .\n```\n"
            (target_dir / "README.md").write_text(readme_content, encoding="utf-8")
            created_files.append("README.md")

            # 3. main.py
            main_content = "def main():\n    print(f'Hello from {project_name}!')\n\nif __name__ == '__main__':\n    main()\n"
            (target_dir / f"{project_name.replace('-', '_')}" / "main.py").parent.mkdir(exist_ok=True)
            (target_dir / f"{project_name.replace('-', '_')}" / "main.py").write_text(main_content, encoding="utf-8")
            created_files.append(f"{project_name.replace('-', '_')}/main.py")

            # 4. pyproject.toml
            pyproject_content = f'[build-system]\nrequires = ["setuptools>=61.0"]\nbuild-backend = "setuptools.build_meta"\n\n[project]\nname = "{project_name}"\nversion = "0.1.0"\ndescription = "Auto-generated project"\nrequires-python = ">=3.10"\n\n[project.scripts]\n{project_name.replace("-", "_")} = "{project_name.replace("-", "_")}.main:main"\n'
            (target_dir / "pyproject.toml").write_text(pyproject_content, encoding="utf-8")
            created_files.append("pyproject.toml")

            return ToolResult(
                True, 
                self.name, 
                f"SUCCESS: Created project '{project_name}' at {target_dir}\nFiles: {', '.join(created_files)}", 
                None
            )
            
        except Exception as e:
            return ToolResult(False, self.name, f"ERROR: {type(e).__name__}: {str(e)}", None)
